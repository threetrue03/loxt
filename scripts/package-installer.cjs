// Extend the stock NSIS section while retaining builder's separate uninstaller
// compilation. A custom nsis.script disables that compilation in electron-builder.
const { readFileSync, writeFileSync } = require('node:fs');
const path = require('node:path');
const { build, Platform, Arch } = require('electron-builder');
const { NsisTarget } = require('app-builder-lib/out/targets/nsis/NsisTarget');

function replaceOnce(source, before, after) {
  if (source.split(before).length !== 2) throw new Error('NSIS template changed: ' + before);
  return source.replace(before, after);
}
const templates = path.dirname(require.resolve('app-builder-lib/templates/nsis/installer.nsi'));
let assisted = readFileSync(path.join(templates, 'assistedInstaller.nsh'), 'utf8').replace(/\r\n/g, '\n');
assisted = replaceOnce(assisted, '!insertmacro skipPageIfUpdated\n    !insertmacro MUI_PAGE_DIRECTORY',
  '!define MUI_PAGE_CUSTOMFUNCTION_PRE SorinoteDirectoryPre\n    !insertmacro MUI_PAGE_DIRECTORY');
assisted = replaceOnce(assisted, 'Function instFilesPre',
  'Function instFilesPre\n      ${If} $SorinoteAction == "repair"\n      ${OrIf} $SorinoteAction == "update"\n      ${OrIf} $SorinoteAction == "delete"\n        Return\n      ${EndIf}');
assisted = replaceOnce(assisted, '!insertmacro MUI_PAGE_INSTFILES',
  '!insertmacro MUI_PAGE_INSTFILES\n  Page custom SorinotePreparationProgressPage SorinotePreparationProgressLeave');
writeFileSync(path.join(__dirname, '../build/assistedInstaller.nsh'), '; Generated by scripts/package-installer.cjs\n' + assisted);

const original = NsisTarget.prototype.computeFinalScript;
NsisTarget.prototype.computeFinalScript = function (script, isInstaller, archs) {
  script = replaceOnce(script, '!include "assistedInstaller.nsh"', '!include "${PROJECT_DIR}\\build\\assistedInstaller.nsh"');
  script = replaceOnce(script, "    # If we're running a silent upgrade", '    Call SorinoteGuard\n    ${If} $SorinoteAction == "delete"\n      Call SorinoteDeleteApp\n    ${Else}\n    # If we\'re running a silent upgrade');
  script = replaceOnce(script, '!include "installSection.nsh"', '!include "installSection.nsh"\n    ${EndIf}');
  return original.call(this, script, isInstaller, archs);
};
const prepackaged = process.argv[2];
build({ targets: Platform.WINDOWS.createTarget('nsis', Arch.x64),
  ...(prepackaged ? { prepackaged: path.resolve(prepackaged) } : {}) }).catch(error => {
  console.error(error); process.exit(1);
});
