import { _electron as electron } from 'playwright';
import assert from 'node:assert/strict';
import { mkdir, mkdtemp, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { Library } from '../electron/library.cjs';
import { waveHeader } from '../electron/pcm-wave.cjs';

const version = JSON.parse(await readFile('package.json', 'utf8')).version;
const out = path.resolve(`test-results/recording-review-${version}`);
await mkdir(out, { recursive: true });
const profile = await mkdtemp(path.join(out, 'profile-'));
const library = new Library(path.join(profile, 'library')); await library.ready;
await library.createFolder('회의');
const source = path.join(profile, 'sample.wav');
await writeFile(source, Buffer.concat([waveHeader(32000 * 30), Buffer.alloc(32000 * 30)]));
const env = { ...process.env, SORINOTE_TEST: '1', SORINOTE_TEST_DATA: profile };
delete env.ELECTRON_RUN_AS_NODE; delete env.SORINOTE_DEV;
const executablePath = process.argv.slice(2).find(value => value.endsWith('.exe'));
const results = { version, profile, packaged: Boolean(executablePath), fixture: 'Private profile, silent fake microphone and intercepted inference request. No physical microphone or GPU verification.' };
let app, page; const errors = [];
try {
  app = await electron.launch({ ...(executablePath ? { executablePath: path.resolve(executablePath) } : {}), args: [...(executablePath ? [] : ['.']), '--use-fake-device-for-media-stream', `--use-file-for-fake-audio-capture=${source}`], env });
  page = await app.firstWindow(); page.setDefaultTimeout(15000); page.on('pageerror', error => errors.push(error.stack));
  await app.evaluate(({ BrowserWindow, dialog }) => { BrowserWindow.getAllWindows()[0].setSize(1440, 900); dialog.showMessageBox = async () => ({ response: 0 }); });
  const work = page.locator('[data-workspace="work"]');
  const dialog = page.getByRole('dialog', { name: '변환하기', exact: true });
  const clock = work.locator('.clock');
  await work.getByRole('heading', { name: '홈', exact: true }).waitFor();
  const environment = await page.evaluate(() => window.desktop.getTranscriptionEnvironment());
  await app.evaluate(({ ipcMain, BrowserWindow }, environment) => {
    global.reviewTestRequests = [];
    ipcMain.removeHandler('transcription:start');
    ipcMain.handle('transcription:start', (_event, payload) => { global.reviewTestRequests.push(payload); return environment; });
    ipcMain.removeHandler('transcription:environment');
    ipcMain.handle('transcription:environment', () => environment);
    BrowserWindow.getAllWindows()[0].webContents.send('transcription:state', environment);
  }, { ...environment, busy: false, models: environment.models.map(model => ({ ...model, downloaded: true })) });
  await work.locator('.home-start-action').filter({ hasText: '새 녹음' }).click();
  await work.getByLabel('녹음 제목', { exact: true }).fill('중단 후 변환 검증');
  await work.getByRole('button', { name: '녹음 시작', exact: true }).click();
  await work.getByRole('button', { name: '녹음 중단', exact: true }).waitFor();
  await page.waitForFunction(() => document.querySelector('[data-workspace="work"] .clock').textContent >= '00:00:02');
  await work.getByRole('button', { name: '메모 열기', exact: true }).click();
  await work.locator('.memo-panel .bn-inline-content').click(); await page.keyboard.type('중단과 재개 뒤에도 메모 보존');
  await work.getByRole('button', { name: '녹음 중단', exact: true }).click();
  await work.getByRole('button', { name: '변환하기', exact: true }).waitFor();
  assert.equal(await dialog.count(), 0);
  const stoppedTime = await clock.innerText(); await page.waitForTimeout(1200); assert.equal(await clock.innerText(), stoppedTime);
  assert.equal(await app.evaluate(() => global.reviewTestRequests.length), 0);
  results.stopSavesWithoutDialogOrInference = true;
  await page.mouse.move(1400, 80);
  const screenshot = await app.evaluate(async ({ BrowserWindow }) => (await BrowserWindow.getAllWindows()[0].webContents.capturePage()).toPNG().toString('base64'));
  await writeFile(path.join(out, executablePath ? 'packaged-ready.png' : 'source-ready.png'), Buffer.from(screenshot, 'base64'));
  await work.getByRole('button', { name: '변환하기', exact: true }).click(); await dialog.waitFor();
  await dialog.getByRole('button', { name: '닫기', exact: true }).click();
  assert.equal(await dialog.count(), 0); assert.ok(await work.getByRole('button', { name: '변환하기', exact: true }).isEnabled());
  await page.getByRole('button', { name: '워크스페이스 선택', exact: true }).click(); await page.getByRole('menuitemradio', { name: /^Live/ }).click();
  await page.getByRole('button', { name: '워크스페이스 선택', exact: true }).click(); await page.getByRole('menuitemradio', { name: /^Work/ }).click();
  assert.equal(await clock.innerText(), stoppedTime); assert.equal(await dialog.count(), 0);
  assert.ok(await work.getByRole('button', { name: '변환하기', exact: true }).isEnabled());
  results.closeAndNavigateKeepStoppedConversionReady = true;
  assert.equal(await work.getByRole('button', { name: '녹음 계속', exact: true }).count(),0);
  assert.ok(await work.getByRole('button', { name: '버리기', exact: true }).isEnabled());
  await work.getByRole('button', { name: '변환하기', exact: true }).click();
  await dialog.getByRole('button', { name: '회의', exact: true }).click();
  await dialog.getByRole('button', { name: '변환하기', exact: true }).click();
  await work.getByLabel('녹음 제목 변경', { exact: true }).waitFor();
  const saved = (await page.evaluate(() => window.desktop.getLibrary())).notes.find(note => note.title === '중단 후 변환 검증');
  assert.ok(saved); assert.equal(saved.folder, '회의'); assert.ok(saved.seconds >= 2);
  assert.match(JSON.stringify((await page.evaluate(id => window.desktop.memos.get(id), saved.id)).blocks), /중단과 재개 뒤에도 메모 보존/);
  const requests = await app.evaluate(() => global.reviewTestRequests); assert.equal(requests.length, 1); assert.equal(requests[0].id, saved.id);
  results.confirmPreservesSavedAudioMemoAndEnqueuesOnce = true;
  await work.locator('.sidebar-create').click(); await work.getByRole('button', { name: '녹음 시작', exact: true }).click();
  await work.getByRole('button', { name: '녹음 중단', exact: true }).click();
  await work.getByRole('button', { name: '버리기', exact: true }).waitFor();
  assert.equal(await dialog.count(), 0);
  await work.getByRole('button', { name: '버리기', exact: true }).click();
  await work.getByRole('heading', { name: '홈', exact: true }).waitFor();
  assert.equal((await page.evaluate(() => window.desktop.getLibrary())).notes.length, 1);
  assert.equal(await app.evaluate(() => global.reviewTestRequests.length), 1); results.discardWithoutInference = true;
  assert.deepEqual(errors, []); results.passed = true; await app.close(); app = null;
} catch (error) {
  results.error = error.stack;
  if (page) { results.alerts = await page.locator('.error-message:visible').allTextContents().catch(() => []); await page.screenshot({ path: path.join(out, 'failure.png') }).catch(() => {}); }
  throw error;
} finally {
  results.errors = errors; await writeFile(path.join(out, executablePath ? 'packaged.json' : 'source.json'), JSON.stringify(results, null, 2));
  if (app) await app.evaluate(({ app }) => app.exit(0)).catch(() => {});
}
